#!/usr/bin/env python3
"""Prepare leakage-safe, quality-filtered SFT data from the approved hint bank.

This is self-distillation: most response targets were generated by the same base model.
The output must not be described as human-corrected data or independent quality labels.

Example:
  python assist/ft/prepare_dataset.py --output-dir results/qwen3_06b_lora_v1/prepared
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import random
import re
from collections import Counter, defaultdict
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from assist.prompts import PROMPT_VERSION, SYSTEM, build_user_prompt
from assist.validator import load_solutions, load_tasks, validate

MODEL_ID = "Qwen/Qwen3-0.6B"
MODEL_REVISION = "c1899de289a04d12100db370d81485cdf75e47ca"
ABSTRACT_HEAD = re.compile(r"\bAbstract\s*(?:\([^)]*\))?\s*:\s*", re.I)
SENTENCE_MARKER = re.compile(r"\[\d+\]")
TOKEN = re.compile(r"[a-z0-9]+")


class UnionFind:
    def __init__(self):
        self.parent: dict[str, str] = {}

    def add(self, x: str) -> None:
        self.parent.setdefault(x, x)

    def find(self, x: str) -> str:
        self.add(x)
        if self.parent[x] != x:
            self.parent[x] = self.find(self.parent[x])
        return self.parent[x]

    def union(self, a: str, b: str) -> None:
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.parent[max(ra, rb)] = min(ra, rb)


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def norm_text(text: str) -> str:
    text = SENTENCE_MARKER.sub(" ", text.lower())
    return " ".join(TOKEN.findall(text))


def abstract_text(task: dict) -> str:
    prompt = task.get("prompt", "")
    match = ABSTRACT_HEAD.search(prompt)
    if not match:
        return ""
    return norm_text(prompt[match.end():])


def shingles(text: str, n: int = 5) -> set[tuple[str, ...]]:
    words = text.split()
    return {tuple(words[i:i + n]) for i in range(max(0, len(words) - n + 1))}


def make_splits(tasks: dict[str, dict], seed: int, ratios: dict[str, float]):
    """Split base tasks by task-transfer pair and exact/near-duplicate science abstract."""
    base = {tid: t for tid, t in tasks.items() if not tid.endswith("_T")}
    uf = UnionFind()
    for tid, task in base.items():
        uf.add(tid)
        transfer_id = task.get("transfer_task_id")
        if transfer_id in tasks:
            uf.union(tid, transfer_id)

    signatures: dict[str, str] = {}
    shingles_by_task: dict[str, set[tuple[str, ...]]] = {}
    for tid, task in base.items():
        if task["domain"] != "science":
            continue
        text = abstract_text(task)
        if not text:
            continue
        signatures[tid] = hashlib.sha256(text.encode()).hexdigest()
        shingles_by_task[tid] = shingles(text)

    # Exact duplicate abstracts are always grouped; near duplicates are grouped at a conservative
    # 0.95 Jaccard threshold over five-token shingles. This prevents shared abstract content crossing splits.
    prior: list[str] = []
    for tid in sorted(signatures):
        for other in prior:
            if signatures[tid] == signatures[other]:
                uf.union(tid, other)
                continue
            a, b = shingles_by_task[tid], shingles_by_task[other]
            if a and b and len(a & b) / len(a | b) >= 0.95:
                uf.union(tid, other)
        prior.append(tid)

    groups: dict[str, list[str]] = defaultdict(list)
    for tid in base:
        groups[uf.find(tid)].append(tid)

    # Each domain is stratified independently. A size-aware greedy assignment keeps task counts
    # close to 70/15/15 without breaking pair or abstract clusters.
    rng = random.Random(seed)
    split_for_group: dict[str, str] = {}
    for domain in ("coding", "science"):
        domain_groups = [sorted(members) for members in groups.values()
                         if base[members[0]]["domain"] == domain]
        rng.shuffle(domain_groups)
        # Stable sort keeps the seeded shuffle order among equal-sized groups.
        domain_groups.sort(key=lambda members: -len(members))
        counts = Counter()
        for members in domain_groups:
            target_split = min(("train", "dev", "test"), key=lambda s: (counts[s] / ratios[s], ("train", "dev", "test").index(s)))
            group_key = hashlib.sha256("|".join(members).encode()).hexdigest()[:12]
            split_for_group[group_key] = target_split
            counts[target_split] += len(members)
            for member in members:
                groups[member] = members  # stable reverse lookup for manifest below

    task_to_split: dict[str, str] = {}
    task_to_group: dict[str, str] = {}
    for members in {tuple(v) for v in groups.values()}:
        group_key = hashlib.sha256("|".join(members).encode()).hexdigest()[:12]
        split = split_for_group[group_key]
        for tid in members:
            task_to_split[tid] = split
            task_to_group[tid] = group_key

    # Copy split and group assignment to every transfer record as well.
    full_task_split, full_task_group = {}, {}
    for tid, task in base.items():
        split, group_key = task_to_split[tid], task_to_group[tid]
        full_task_split[tid] = split
        full_task_group[tid] = group_key
        transfer_id = task.get("transfer_task_id")
        if transfer_id in tasks:
            full_task_split[transfer_id] = split
            full_task_group[transfer_id] = group_key

    # Explicit assertions guard both task-pair and exact-abstract leakage.
    for tid, task in base.items():
        transfer_id = task.get("transfer_task_id")
        if transfer_id in full_task_split and full_task_split[tid] != full_task_split[transfer_id]:
            raise RuntimeError(f"task-transfer leakage: {tid} vs {transfer_id}")
    hash_splits: dict[str, set[str]] = defaultdict(set)
    for tid, fingerprint in signatures.items():
        hash_splits[fingerprint].add(full_task_split[tid])
    leaked = [fingerprint for fingerprint, splits in hash_splits.items() if len(splits) > 1]
    if leaked:
        raise RuntimeError(f"{len(leaked)} exact science abstracts cross splits")

    manifest = []
    for tid, task in sorted(base.items()):
        transfer_id = task.get("transfer_task_id", "")
        manifest.append({
            "base_task_id": tid,
            "transfer_task_id": transfer_id,
            "domain": task["domain"],
            "split": full_task_split[tid],
            "group_id": full_task_group[tid],
            "science_abstract_sha256": signatures.get(tid, ""),
        })
    return base, full_task_split, full_task_group, signatures, manifest


def write_jsonl(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--train-ratio", type=float, default=0.70)
    ap.add_argument("--dev-ratio", type=float, default=0.15)
    ap.add_argument("--test-ratio", type=float, default=0.15)
    ap.add_argument("--output-dir", default="results/qwen3_06b_lora_v1/prepared")
    ap.add_argument("--tasks", default="data/tasks.jsonl")
    ap.add_argument("--solutions", default="data/solutions.jsonl")
    ap.add_argument("--hints", default="data/hints.jsonl")
    a = ap.parse_args()
    ratios = {"train": a.train_ratio, "dev": a.dev_ratio, "test": a.test_ratio}
    if any(v <= 0 for v in ratios.values()) or abs(sum(ratios.values()) - 1.0) > 1e-6:
        ap.error("train/dev/test ratios must be positive and sum to 1")

    task_path, solution_path, hint_path = (ROOT / getattr(a, name) for name in ("tasks", "solutions", "hints"))
    tasks = load_tasks(task_path)
    solutions = load_solutions(solution_path)
    base, task_split, task_group, abstract_hashes, manifest = make_splits(tasks, a.seed, ratios)
    out = ROOT / a.output_dir
    out.mkdir(parents=True, exist_ok=True)

    with (out / "split_manifest.csv").open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(manifest[0]), lineterminator="\n")
        writer.writeheader(); writer.writerows(manifest)

    hints = [json.loads(line) for line in hint_path.open(encoding="utf-8") if line.strip()]
    examples = {split: [] for split in ratios}
    counts = Counter()
    seen = set()
    for hint in hints:
        tid, op, level = hint["task_id"], hint["op"], int(hint["level"])
        if tid not in base:
            counts["ignored_transfer_or_unknown"] += 1; continue
        key = (tid, op, level)
        if key in seen:
            raise RuntimeError(f"duplicate hint key in bank: {key}")
        seen.add(key)
        source = hint.get("source", "")
        if source not in {"qwen", "handwritten"}:
            counts[f"excluded_source_{source or 'missing'}"] += 1; continue
        task = base[tid]
        verdict = validate(task, op, level, hint["text"], solutions.get(tid))
        if verdict["leakage_flag"] or not verdict["compliance_flag"]:
            counts["excluded_invalid_by_current_validator"] += 1; continue
        split = task_split[tid]
        user = build_user_prompt(task, op, level, solutions.get(tid))
        example_id = hashlib.sha256(f"{tid}|{op}|{level}|{hint['text']}".encode()).hexdigest()[:20]
        examples[split].append({
            "example_id": example_id,
            "task_id": tid,
            "group_id": task_group[tid],
            "domain": task["domain"],
            "op": op,
            "level": level,
            "system": SYSTEM,
            "user": user,
            "response": hint["text"],
            "source": source,
            "target_provenance": "base_model_pseudolabel" if source == "qwen" else "handwritten",
        })
        counts[f"included_{source}"] += 1

    for split, rows in examples.items():
        rows.sort(key=lambda r: (r["task_id"], r["op"], r["level"]))
        write_jsonl(out / f"{split}.jsonl", rows)
        if not rows:
            raise RuntimeError(f"empty {split} split after quality filtering")

    summary = {
        "dataset_version": "qwen3_06b_lora_v1",
        "base_model": MODEL_ID,
        "base_model_revision": MODEL_REVISION,
        "prompt_version": PROMPT_VERSION,
        "seed": a.seed,
        "split_ratios_requested": ratios,
        "split_base_task_counts": {s: sum(task_split[t] == s for t in base) for s in ratios},
        "split_task_counts_including_transfers": {s: sum(v == s for v in task_split.values()) for s in ratios},
        "split_group_counts": {s: len({task_group[t] for t in base if task_split[t] == s}) for s in ratios},
        "examples_by_split": {s: len(rows) for s, rows in examples.items()},
        "examples_by_domain_and_split": {
            f"{domain}_{split}": sum(r["domain"] == domain for r in examples[split])
            for domain in ("coding", "science") for split in ratios
        },
        "examples_by_level_and_split": {
            f"L{level}_{split}": sum(r["level"] == level for r in examples[split])
            for level in (1, 2, 3, 4) for split in ratios
        },
        "source_filter_counts": dict(counts),
        "science_exact_abstract_count": len(abstract_hashes),
        "science_abstract_near_duplicate_threshold": 0.95,
        "source_file_sha256": {
            "tasks": sha256_file(task_path), "solutions": sha256_file(solution_path), "hints": sha256_file(hint_path),
        },
        "filtering": "Retain only Qwen or handwritten base-task hints that pass the current rule-based compliance and leakage validator. Exclude fallback outputs. This is an automatic filter, not a human correctness judgment.",
        "target_limitation": "Qwen targets are self-distillation pseudo-labels from the base model; improvements in the same validator do not establish pedagogical or factual improvement.",
    }
    (out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
